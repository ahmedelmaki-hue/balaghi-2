def set_cell_fill(cell, hex_color):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:fill'), hex_color)
    tc_pr.append(shd)

def set_cell_border(cell):
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement('w:tcBorders')
    for edge in ('top', 'left', 'bottom', 'right'):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '5')
        el.set(qn('w:color'), 'D9D9D9')
        borders.append(el)
    tc_pr.append(borders)

def set_cell_margins(cell, top=110, start=120, bottom=110, end=120):
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    mar = OxmlElement('w:tcMar')
    for name, value in [('top', top), ('start', start), ('bottom', bottom), ('end', end)]:
        x = OxmlElement(f'w:{name}')
        x.set(qn('w:w'), str(value))
        x.set(qn('w:type'), 'dxa')
        mar.append(x)
    tc_pr.append(mar)

def rtl_paragraph(p):
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_pr = p._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    bidi.set(qn('w:val'), '1')
    p_pr.append(bidi)

def add_rtl_run(p, value, bold=False, color=INK, size=None):
    r = p.add_run(value)
    r.bold = bold
    r.font.name = 'Arial'
    r.font.color.rgb = color
    if size:
        r.font.size = Pt(size)
    r_pr = r._element.get_or_add_rPr()
    rtl = OxmlElement('w:rtl')
    rtl.set(qn('w:val'), '1')
    r_pr.append(rtl)
    return r

def style(name, size, bold=False, before=0, after=0, line=1.22):
    s = doc.styles[name] if name in doc.styles else doc.styles.add_style(name, WD_STYLE_TYPE.PARAGRAPH)
    s.font.name = 'Arial'
    s.font.size = Pt(size)
    s.font.bold = bold
    s.font.color.rgb = RGBColor(0, 0, 0)
    s.paragraph_format.space_before = Pt(before)
    s.paragraph_format.space_after = Pt(after)
    s.paragraph_format.line_spacing = line
    return s

